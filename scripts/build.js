/**
 * Build script for EduMarket.
 *
 *   npm run build   -> app.js + app.css (minified, served by index.html) + db/seed-data.js (seed for the server)
 *   npm run watch   -> same, unminified with inline source maps, rebuilds on every save in src/
 *
 * Source of truth is src/ (JS in src/**, CSS in src/styles/). Never edit app.js, app.css or
 * db/seed-data.js by hand — they are overwritten.
 */
const path = require('path');
const esbuild = require('esbuild');

const root = path.join(__dirname, '..');
const watch = process.argv.includes('--watch');

const appOptions = {
  entryPoints: [path.join(root, 'src/index.jsx')],
  outfile: path.join(root, 'app.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'automatic',
  charset: 'utf8',
  minify: !watch,
  sourcemap: watch ? 'inline' : false,
  legalComments: 'eof',
  define: { 'process.env.NODE_ENV': watch ? '"development"' : '"production"' },
  logLevel: 'info',
};

// Styles: src/styles/index.css (legacy + design layers) -> app.css
const cssOptions = {
  entryPoints: [path.join(root, 'src/styles/index.css')],
  outfile: path.join(root, 'app.css'),
  bundle: true,
  minify: !watch,
  target: ['safari14', 'chrome90', 'firefox90'],
  charset: 'utf8',
  // Images under /assets are served by server.js as-is; keep their URLs untouched.
  external: ['/assets/*'],
  logLevel: 'info',
};

// Seed data shared with the Node server (db/supabase.js -> getSeedData()).
const seedOptions = {
  entryPoints: [path.join(root, 'src/data/seed.js')],
  outfile: path.join(root, 'db/seed-data.js'),
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: ['node18'],
  charset: 'utf8',
  banner: {
    js: '// AUTO-GENERATED by `npm run build` from src/data/seed.js — do not edit by hand.',
  },
  logLevel: 'info',
};

async function main() {
  if (watch) {
    const contexts = await Promise.all([appOptions, cssOptions, seedOptions].map((o) => esbuild.context(o)));
    await Promise.all(contexts.map((ctx) => ctx.watch()));
    console.log('[build] watching src/ for changes… (Ctrl+C to stop)');
    return;
  }
  await Promise.all([esbuild.build(appOptions), esbuild.build(cssOptions), esbuild.build(seedOptions)]);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
